export const DETAIL_ON_REQUEST = "On request";

interface CatalogGemInput {
  slug: string;
  name: string;
  category: string;
  variety: string;
  color: string;
  cut: string;
  images: string[];
  description: string;
  /** Leave unset (0) to show "Weight on request". */
  carat?: number;
  /** Leave unset (0) to show "Price on request" and disable add-to-cart. */
  price?: number;
  featured?: boolean;
}

function catalogGem(input: CatalogGemInput): Gemstone {
  return {
    id: input.slug,
    slug: input.slug,
    name: input.name,
    variety: input.variety,
    category: input.category,
    carat: input.carat ?? 0,
    origin: "Ceylon (Sri Lanka)",
    cut: input.cut,
    dimensions: DETAIL_ON_REQUEST,
    color: input.color,
    treatment: DETAIL_ON_REQUEST,
    clarity: DETAIL_ON_REQUEST,
    price: input.price ?? 0,
    currency: "USD",
    inStock: true,
    featured: input.featured ?? false,
    description: input.description,
    certificate: { lab: "", number: "" },
    images: input.images.map((url, i) => ({
      url,
      alt: `${input.name} - photo ${i + 1}`,
    })),
  };
}

